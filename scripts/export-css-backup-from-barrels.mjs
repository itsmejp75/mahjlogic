/**
 * Writes `backup folder/safe_backup.css` by concatenating every fragment listed
 * in `src/styles/{base,layout,components,animations}.css` — i.e. the same CSS
 * Vite bundles for localhost / production.
 *
 * Use this **after** you have edited `src/styles/fragments/part-*.css` and want
 * `npm run split-css` to stop reverting you: run `export-css-backup` first so
 * the backup matches Git, then split-css (if you still need to re-partition).
 *
 * Note: `split-css` re-splits by rule boundaries and may produce a *different*
 * number of part files than today; for day-to-day work, prefer editing fragments
 * directly and **do not run split-css** unless you intend to regenerate from backup.
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const stylesDir = path.join(root, 'src', 'styles')
const outPath = path.join(root, 'backup folder', 'safe_backup.css')
const barrels = ['base.css', 'layout.css', 'components.css', 'animations.css']

const importRe = /@import\s+["']\.\/fragments\/([^"']+)["']\s*;/

const seen = new Set()
const parts = []

for (const barrel of barrels) {
  const p = path.join(stylesDir, barrel)
  const text = fs.readFileSync(p, 'utf8')
  for (const line of text.split('\n')) {
    const m = line.match(importRe)
    if (!m) continue
    const name = m[1]
    if (seen.has(name)) {
      console.warn('duplicate import (skipped):', name, 'in', barrel)
      continue
    }
    seen.add(name)
    parts.push(name)
  }
}

if (!parts.length) {
  console.error('export-css-backup: no @import ./fragments/… found in barrels')
  process.exit(1)
}

const chunks = []
for (const name of parts) {
  const fragPath = path.join(stylesDir, 'fragments', name)
  if (!fs.existsSync(fragPath)) {
    console.error('missing fragment:', fragPath)
    process.exit(1)
  }
  const body = fs.readFileSync(fragPath, 'utf8').replace(/\s+$/, '')
  chunks.push(`/* ---- ${name} (from ${barrels.join(', ')}) ---- */\n\n${body}`)
}

const header = `/*
 * Generated by scripts/export-css-backup-from-barrels.mjs
 * Do not edit by hand unless you know split-css will overwrite fragments from this file.
 * Fragment sources: ${parts.length} files concatenated in barrel import order.
 */\n\n`

fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, header + chunks.join('\n\n') + '\n', 'utf8')
console.log('wrote', outPath, 'from', parts.length, 'fragments')
